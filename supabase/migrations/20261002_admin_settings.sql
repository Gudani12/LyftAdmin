alter table public.admin
  add column if not exists status text not null default 'active',
  add column if not exists archive_reason text,
  add column if not exists archived_at timestamptz;

create or replace function public.is_lyft_admin()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.admin as admin_user
    where admin_user.clerk_id = (select auth.jwt() ->> 'sub')
      and admin_user.role in ('super_admin', 'verifier', 'support', 'finance')
      and admin_user.status = 'active'
  );
$$;

revoke all on function public.is_lyft_admin() from public;
grant execute on function public.is_lyft_admin() to authenticated;

