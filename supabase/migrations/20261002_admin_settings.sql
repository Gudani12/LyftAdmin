alter table public.admin enable row level security;
revoke all on table public.admin from anon, authenticated, public;
grant select, delete on table public.admin to authenticated;
grant update (status, archive_reason, archived_at) on table public.admin to authenticated;

do $$
declare
  existing_policy record;
begin
  for existing_policy in
    select policyname from pg_policies where schemaname = 'public' and tablename = 'admin'
  loop
    execute format('drop policy %I on public.admin', existing_policy.policyname);
  end loop;
end
$$;

create policy "Users can read their own admin profile"
  on public.admin
  for select
  to authenticated
  using (clerk_id = (select auth.jwt() ->> 'sub') or public.is_lyft_super_admin());

create policy "Super admins can update admin account status"
  on public.admin
  for update
  to authenticated
  using (public.is_lyft_super_admin())
  with check (public.is_lyft_super_admin());

create policy "Super admins can delete admin accounts"
  on public.admin
  for delete
  to authenticated
  using (public.is_lyft_super_admin());

