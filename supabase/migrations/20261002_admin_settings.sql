  admin_name text not null,
  admin_role text not null,
  action text not null,
  target text not null,
  created_at timestamptz not null default now()
);

create or replace function public.set_admin_audit_actor()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  actor public.admin%rowtype;
begin
  select * into actor
  from public.admin
  where clerk_id = (select auth.jwt() ->> 'sub')
    and status = 'active';

  if not found then
    raise exception 'An active admin account is required to write audit history';
  end if;

  new.admin_clerk_id := actor.clerk_id;
  new.admin_name := coalesce(actor.full_name, actor.email, actor.clerk_id);
  new.admin_role := actor.role;
  return new;
end;
$$;

revoke all on function public.set_admin_audit_actor() from public;

drop trigger if exists set_admin_audit_actor on public.admin_audit_log;
create trigger set_admin_audit_actor
  before insert on public.admin_audit_log
  for each row execute function public.set_admin_audit_actor();

